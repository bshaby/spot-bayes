def set_domain(ax):
    ax.set_xlim(MIN_LON - 0.4, MAX_LON + 0.4)
    ax.set_ylim(MIN_LAT - 0.4, MAX_LAT + 0.4)
    ax.set_aspect("equal")
    ax.set_xlabel("Longitude")
    ax.set_ylabel("Latitude")


def _grid_axes(inp):
    """Sorted unique lon/lat of the (regular 0.5deg) site grid."""
    return np.unique(inp["lon"]), np.unique(inp["lat"])


def cell_edges(centers):
    """Cell-edge coordinates from a vector of regular cell centers."""
    c = np.asarray(centers, float)
    e = np.empty(c.size + 1)
    e[1:-1] = 0.5 * (c[:-1] + c[1:])
    e[0] = c[0] - (c[1] - c[0]) / 2.0
    e[-1] = c[-1] + (c[-1] - c[-2]) / 2.0
    return e


def grid_from_sites(inp, values, fill=np.nan):
    """Scatter per-site values onto the full regular (lat, lon) grid (gaps = fill)."""
    glon, glat = _grid_axes(inp)
    g = np.full((glat.size, glon.size), fill, dtype=float)
    ix = np.searchsorted(glon, inp["lon"])
    iy = np.searchsorted(glat, inp["lat"])
    g[iy, ix] = values
    return g, glon, glat


def plot_cells(ax, inp, values, cmap="viridis", vmin=None, vmax=None, bad="0.85"):
    """Filled cell map of a per-site quantity over the domain (off-grid gaps greyed)."""
    import matplotlib
    grid, glon, glat = grid_from_sites(inp, values)
    grid = np.ma.masked_invalid(grid)
    cm = matplotlib.colormaps[cmap].copy() if isinstance(cmap, str) else cmap.copy()
    cm.set_bad(bad)
    return ax.pcolormesh(cell_edges(glon), cell_edges(glat), grid,
                         cmap=cm, vmin=vmin, vmax=vmax, zorder=1)
