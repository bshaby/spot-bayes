# -- polygons -----------------------------------------------------------------
_BARRIER = None


def barrier_polygon():
    """The 1500 m Southern-Alps contour as a single shapely Polygon (cached)."""
    global _BARRIER
    if _BARRIER is None:
        import geopandas as gpd
        gdf = gpd.read_file(BARRIER_SHP)
        _BARRIER = gdf.union_all() if hasattr(gdf, "union_all") else gdf.unary_union
    return _BARRIER


def _inner_box():
    from shapely.geometry import Polygon
    return Polygon([(MIN_LON - 0.1, MIN_LAT - 0.1), (MAX_LON + 0.1, MIN_LAT - 0.1),
                    (MAX_LON + 0.1, MAX_LAT + 0.1), (MIN_LON - 0.1, MAX_LAT + 0.1)])


def modeling_polygon():
    """Modelling domain = inner boundary box MINUS the barrier (mountain obstacle).
    Used for the Wang visibility graph and the barrier Wendland kernels. Precip is
    defined on both flanks, so -- unlike Faroe's ocean-only domain -- this keeps
    both windward and leeward sites; only the impermeable high-alpine interior is
    removed."""
    return _inner_box().difference(barrier_polygon())


# -- knots --------------------------------------------------------------------
def _reference_centers(nx_in, ny_in, nx_out, ny_out):
    """Faroe-style interleaved inner mesh (barrier-excluded, in-domain) + outer ring.

    Generalised to rectangular per-axis counts for the (non-square) NZ domain:
      * inner : two interleaved nx_in x ny_in meshes over the domain box; keep those
                strictly in-domain and OUTSIDE the barrier polygon;
      * outer : an nx_out x ny_out linspace over the padded outer box; keep those
                OUTSIDE the inner box (a ring). With a 4x4 outer grid this gives the
                4 corners + 2 evenly-spaced knots per edge.
    """
    from shapely.geometry import Point
    bar = barrier_polygon()
    box = _inner_box()
    xd = (MAX_LON - MIN_LON) / (nx_in - 1)
    yd = (MAX_LAT - MIN_LAT) / (ny_in - 1)
    xc = np.linspace(MIN_LON + xd / 2, MAX_LON + xd / 2, num=nx_in)
    yc = np.linspace(MIN_LAT + yd / 2, MAX_LAT + yd / 2, num=ny_in)
    Xo, Yo = np.meshgrid(xc[0::2], yc[0::2])
    Xi, Yi = np.meshgrid(xc[1::2], yc[1::2])
    centers = np.vstack([np.c_[Xo.ravel(), Yo.ravel()], np.c_[Xi.ravel(), Yi.ravel()]])
    keep = [(MIN_LON < c[0] < MAX_LON and MIN_LAT < c[1] < MAX_LAT) for c in centers]
    centers = centers[np.array(keep)]
    inner = np.array([c for c in centers if not bar.contains(Point(c[0], c[1]))])
    xo = np.linspace(LON_OUTER[0], LON_OUTER[1], nx_out)
    yo = np.linspace(LAT_OUTER[0], LAT_OUTER[1], ny_out)
    Xoo, Yoo = np.meshgrid(xo, yo)
    oc = np.c_[Xoo.ravel(), Yoo.ravel()]
    outer = np.array([c for c in oc if not box.contains(Point(c[0], c[1]))])
    return np.vstack([inner, outer])


def make_knots():
    """(knots_S, knots_phi, knots_rho). S & phi share the Wendland centers (39); rho
    uses the coarser Gaussian centers (24, collapsed to a scalar internally for Wang)."""
    wend = _reference_centers(8, 8, 5, 5)      # 39
    gauss = _reference_centers(6, 6, 4, 4)     # 24
    return wend, wend.copy(), gauss


# -- raw data -----------------------------------------------------------------
def load_raw():
    """Load the 3-day-sum field, threshold, marginal surfaces, covariates and beta
    inits over the 309 model sites (the canonical site order shared by the npz,
    covariate CSVs, GEV-MLE table and the visibility-graph node indices)."""
    d = np.load(NPZ, allow_pickle=True)
    lon = d["lon"].astype(float)
    lat = d["lat"].astype(float)
    sites_xy = np.column_stack([lon, lat]).astype(float)
    Ns = sites_xy.shape[0]

    Y = d["blocks"].astype(float).T.copy()                       # (Ns, Nt) 3-day sums
    u_vec = d["threshold_q95"].astype(float)
    sigma_vec = d["sigma_regression"].astype(float)
    xi_vec = d["xi_regression"].astype(float)

    sig_cov = np.loadtxt(SIGMA_COV_CSV, delimiter=",")
    xi_cov = np.loadtxt(XI_COV_CSV, delimiter=",")
    assert np.allclose(sig_cov[:, 0], 1.0), "sigma covariate col 0 not all-ones"
    assert np.allclose(xi_cov[:, 0], 1.0), "xi covariate col 0 not all-ones"
    sigma_spatial = np.ascontiguousarray(sig_cov[:, 1:])         # (Ns, 5) drop intercept
    xi_spatial = np.ascontiguousarray(xi_cov[:, 1:])             # (Ns, 5) drop intercept

    # cross-check the site order against the GEV-MLE table (lon,lat,mu,sigma,xi)
    gev = np.loadtxt(GEV_MLE_CSV, delimiter=",", skiprows=1)
    assert gev.shape[0] == Ns and np.allclose(gev[:, 0], lon) and \
        np.allclose(gev[:, 1], lat), "GEV-MLE site order does not match the npz lon/lat"

    return dict(
        sites_xy=sites_xy, Y=Y, u_vec=u_vec, sigma_vec=sigma_vec, xi_vec=xi_vec,
        sigma_spatial=sigma_spatial, xi_spatial=xi_spatial,
        beta_sigma=d["beta_log_sigma"].astype(float),           # (6,) [b0, 5 spatial]
        beta_xi=d["beta_logit_star_xi"].astype(float),          # (6,) [b0, 5 spatial]
        lat=lat, lon=lon)


# -- train/test split ---------------------------------------------------------
def split_sites_nz(sites_xy):
    """Return an int block-id per site: 0=train, 1=NW ocean, 2=SE leeward."""
    lon, lat = sites_xy[:, 0], sites_xy[:, 1]
    block = np.zeros(sites_xy.shape[0], dtype=int)
    nw = ((lon >= BLOCK_NW["lon_min"]) & (lon <= BLOCK_NW["lon_max"])
          & (lat >= BLOCK_NW["lat_min"]) & (lat <= BLOCK_NW["lat_max"]))
    block[nw] = 1
    for tx, ty in SE_SITES:
        k = int(np.argmin((lon - tx) ** 2 + (lat - ty) ** 2))
        assert abs(lon[k] - tx) < 1e-6 and abs(lat[k] - ty) < 1e-6, \
            f"no model site at SE target ({tx}, {ty})"
        block[k] = 2
    return block


def se_hull_ring(sites_xy, block_id):
    """Closed (n+1, 2) ring of the convex hull of the SE leeward block (for plots)."""
    from scipy.spatial import ConvexHull
    pts = sites_xy[block_id == 2]
    h = ConvexHull(pts)
    return np.vstack([pts[h.vertices], pts[h.vertices][:1]])


