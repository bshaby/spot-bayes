#!/usr/bin/env python3
"""
Shared setup for the New Zealand South Island extreme-precipitation analysis
(HW / Wang / Shi) -- the precipitation analogue of faroe_analysis/faroe_setup.py.

Picks up where the marginal pre-processing (Part I of
nz_analysis/vignette/nz_modeling_vignette.md) leaves off:
it consumes that stage's fitted 0.95-quantile threshold and GPD marginal coefficients, plus
the storm-scale 3-day-sum precipitation field, and assembles everything the
spot-bayes samplers need to fit the three spatial-extremes models.

Imported by every nz_task*.py so the data, knots, train/test split, model configs,
and (for Wang) the junction-tree cliques are identical across the fit, comparison,
and assessment stages. Deterministic given NZ_SEED.

Design decisions (see the plan / conversation):
  * Modelling series  : 3-day precipitation sums (309 sites x 3080 blocks); keeps
                        the provided threshold, p_cens=0.95 and beta inits consistent.
  * Coordinates       : lon/lat in DEGREES (WGS84).
  * Barrier           : the 1500 m Southern-Alps contour (NZ_SI_barrier_1500m.shp).
                        VERIFIED: the pre-built visibility graph is a 1500 m graph
                        (0/309 sites inside, 0/26566 edges cross it), NOT the 1200 m
                        the folder name / NZ vignette claim (12 sites inside, 4908
                        edges cross). Using 1500 m keeps all 309 sites and lets us
                        reuse NZ_SI_adjacency_matrix.csv turnkey.
  * Knots             : Wendland (S & phi) ref(8,8,5,5)=39; Gaussian (rho)
                        ref(6,6,4,4)=24; both barrier-excluded. Reviewed via knots.png.
  * Margins           : TWO-STAGE. Stage 1 (nz_marginal_fit.py) fits the GPD
                        coefficients on the exceedances alone; Tasks 2-5 then hold
                        sigma/xi FIXED at that posterior-mean surface. models() still
                        declares update_GPD_* = True -- nz_fit.py turns them off under
                        --fix-margins -- so a sampled-margin fit remains available.
  * Split             : two holdout blocks -- NW open-ocean (windward) rectangle +
                        an explicit leeward strip hugging the barrier's SE flank.

Env overrides: NZ_OUT, NZ_NITERS(50000), NZ_THIN(10), NZ_SEED,
NZ_Z_SAMPLER(nuts), NZ_NU_RHO_SAMPLER(nuts), NZ_RHO_PRIOR_C(0.5),
NZ_NUTS_WARMUP(50), NZ_NUTS_TARGET_ACCEPT(0.8), NZ_EFF_RANGE_PHI(1.0),
NZ_EFF_RANGE_RHO(1.5), NZ_RADIUS_S(1.0), NZ_WANG_BARRIER_KERNELS(1),
NZ_PHI0(0.5), NZ_ALPHA0(2.05), NZ_PLUGIN_INIT(1), NZ_STAGE1_NPZ,
NZ_PROGRESS_EVERY(100).
"""
